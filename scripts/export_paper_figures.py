#!/usr/bin/env python3
"""Export the data behind the paper's figures to web/data/paper-figures.json.

Every number comes from files already in results/ (metrics, statistical tests,
pool ablation, stored runs); nothing is typed by hand. Figures 2 and 3 are
plots of formulas and are computed directly in the web page.

    python scripts/export_paper_figures.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from biomedical_ir.evaluation import load_run_json  # noqa: E402

SYSTEMS = [
    ("tfidf", "TF-IDF"),
    ("bm25", "BM25"),
    ("bge", "BGE"),
    ("medcpt", "MedCPT"),
    ("hybrid_rrf", "Hybrid RRF"),
    ("hybrid_reranked", "Hybrid + cross-encoder"),
]
OUT = ROOT / "web" / "data" / "paper-figures.json"


def r4(x: float) -> float:
    return round(float(x), 4)


def main() -> None:
    metrics = {k: json.loads((ROOT / f"results/metrics/{k}.json").read_text()) for k, _ in SYSTEMS}

    recall = [
        {"system": label, "slug": key, "k": k, "value": r4(metrics[key]["metrics"][f"Recall@{k}"])}
        for key, label in SYSTEMS
        for k in (10, 20, 50, 100)
    ]

    cost = []
    for key, label in SYSTEMS:
        ms = metrics[key]["timing"]["latency_ms_per_query"]
        if key == "hybrid_reranked":  # a reranked query also pays for the hybrid first stage
            ms += metrics["hybrid_rrf"]["timing"]["latency_ms_per_query"]
        cost.append({"system": label, "slug": key, "ms": round(ms, 2), "ndcg10": r4(metrics[key]["metrics"]["nDCG@10"])})

    tests = json.loads((ROOT / "results/tables/statistical_tests.json").read_text())["comparisons"]
    rename = {"Hybrid+Reranker": "Reranked"}
    forest = []
    for t in tests:
        a, b = rename.get(t["model_a"], t["model_a"]), rename.get(t["model_b"], t["model_b"])
        # Present every comparison as "later system minus earlier system".
        forest.append({
            "comparison": f"{b} − {a}",
            "metric": t["metric"],
            "diff": r4(-t["mean_diff"]),
            "low": r4(-t["ci_95_high"]),
            "high": r4(-t["ci_95_low"]),
            "p": t["p_value"],
        })

    ablation = json.loads((ROOT / "results/metrics/reranker_pool_ablation.json").read_text())["results_by_pool"]
    pool = [
        {
            "pool": int(p),
            "ndcg10": r4(v["metrics"]["nDCG@10"]),
            "map": r4(v["metrics"]["MAP"]),
            "ms": round(v["reranking_latency_ms_per_query"], 1),
        }
        for p, v in sorted(ablation.items(), key=lambda kv: int(kv[0]))
    ]
    pool_base = {"ndcg10": r4(metrics["hybrid_rrf"]["metrics"]["nDCG@10"]), "map": r4(metrics["hybrid_rrf"]["metrics"]["MAP"])}

    bm25 = load_run_json(ROOT / "results/runs/bm25.json")
    medcpt = load_run_json(ROOT / "results/runs/medcpt.json")
    top_scores = [
        {"query": q, "bm25": round(bm25[q][0][1], 2), "medcpt": round(medcpt[q][0][1], 2)}
        for q in sorted(medcpt)
        if bm25.get(q)
    ]
    hist = [0] * 11
    for q in medcpt:
        shared = {d for d, _ in bm25.get(q, [])[:10]} & {d for d, _ in medcpt[q][:10]}
        hist[len(shared)] += 1
    overlap = [{"shared": i, "queries": n} for i, n in enumerate(hist)]

    OUT.write_text(json.dumps({
        "source": "Generated by scripts/export_paper_figures.py from results/ (NFCorpus test split, 323 queries).",
        "recall": recall,
        "cost": cost,
        "forest": forest,
        "pool": pool,
        "poolBase": pool_base,
        "topScores": top_scores,
        "overlap": overlap,
    }, indent=1, ensure_ascii=False) + "\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(recall)} recall rows, {len(forest)} tests, "
          f"{len(top_scores)} score pairs, overlap histogram over {sum(hist)} queries")


if __name__ == "__main__":
    main()
